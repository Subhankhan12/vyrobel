<?php

namespace Database\Seeders;

use App\Actions\Authorization\OrganizationRoleProvisioner;
use App\Actions\Reservations\CheckOutReservation;
use App\Models\Amenity;
use App\Models\Building;
use App\Models\Floor;
use App\Models\Guest;
use App\Models\Membership;
use App\Models\Organization;
use App\Models\Property;
use App\Models\PropertyPolicy;
use App\Models\RateCalendar;
use App\Models\RatePlan;
use App\Models\Reservation;
use App\Models\RoomType;
use App\Models\Tax;
use App\Models\Unit;
use App\Models\User;
use App\Services\AssignmentService;
use App\Services\AvailabilityService;
use App\Services\FolioService;
use App\Support\Money\Money;
use App\Support\Tenancy\TenantContext;
use Carbon\CarbonImmutable;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\Hash;
use Spatie\Permission\PermissionRegistrar;

/**
 * ONE realistic demo organization with a MIXED property (hotel room types AND apartment units).
 *
 * Everything is unmistakably DEMO (names + the `vyrobel-demo` slug) — never presented as real.
 * Nothing is fabricated: availability is computed by AvailabilityService, `sold` comes from real
 * bookings through AssignmentService, folio totals come from the FolioService ledger, and the
 * departure task is generated by the real checkout event → listener chain.
 */
class DemoSeeder extends Seeder
{
    private const RANGE_START = '2026-09-01';

    private const RANGE_END = '2026-10-01';

    public function run(): void
    {
        $tenant = app(TenantContext::class);

        $org = $tenant->runAsSuperAdmin(fn () => Organization::firstOrCreate(
            ['slug' => 'vyrobel-demo'],
            [
                'name' => 'Vyrobel Demo — Seaside Hotel & Apartments',
                'mode' => 'chain',
                'default_currency' => 'EUR',
                'default_locale' => 'en',
                'country' => 'PT',
                'status' => 'active',
                'billing_email' => 'billing@vyrobel-demo.test',
            ],
        ));

        app(OrganizationRoleProvisioner::class)->provision($org);

        $tenant->forOrganization($org->id, fn () => $this->buildDemo($org));
    }

    private function buildDemo(Organization $org): void
    {
        $owner = User::firstOrCreate(
            ['email' => 'demo-owner@vyrobel-demo.test'],
            ['name' => 'Demo Owner', 'password' => Hash::make('password'), 'status' => 'active'],
        );
        Membership::firstOrCreate(
            ['organization_id' => $org->id, 'user_id' => $owner->id],
            ['status' => 'active', 'invited_at' => now()],
        );
        app(PermissionRegistrar::class)->setPermissionsTeamId($org->id);
        $owner->assignRole('Property Owner');

        // --- Mixed property ---
        $property = Property::create([
            'name' => 'Demo Seaside Property', 'brand' => 'Vyrobel Demo', 'type' => 'mixed',
            'currency' => 'EUR', 'timezone' => 'Europe/Lisbon',
            'check_in_time' => '15:00:00', 'check_out_time' => '11:00:00', 'status' => 'active',
        ]);
        PropertyPolicy::create([
            'property_id' => $property->id,
            'cancellation' => ['type' => 'flexible', 'free_until_days' => 2],
            'pet' => 'on_request', 'smoking' => 'not_allowed', 'min_stay' => 1, 'max_stay' => 30,
        ]);
        $building = Building::create(['property_id' => $property->id, 'name' => 'Main Building', 'code' => 'MB']);
        $floor0 = Floor::create(['building_id' => $building->id, 'level' => 0, 'name' => 'Ground']);
        $floor1 = Floor::create(['building_id' => $building->id, 'level' => 1, 'name' => 'First']);

        $wifi = Amenity::firstOrCreate(['name' => 'WiFi'], ['icon' => 'wifi', 'category' => 'connectivity']);
        $pool = Amenity::firstOrCreate(['name' => 'Pool'], ['icon' => 'pool', 'category' => 'leisure']);

        // Hotel room type + apartment unit type under ONE property.
        $doubleRoom = RoomType::create([
            'property_id' => $property->id, 'name' => 'Double Room', 'code' => 'DBL', 'kind' => 'room',
            'std_occupancy' => 2, 'max_adults' => 2, 'max_children' => 1,
        ]);
        $apartment = RoomType::create([
            'property_id' => $property->id, 'name' => 'One-Bedroom Apartment', 'code' => 'APT', 'kind' => 'apartment',
            'std_occupancy' => 3, 'max_adults' => 3, 'max_children' => 2, 'bedrooms' => 1,
        ]);

        $roomUnits = collect(['101', '102', '103'])->map(fn (string $code) => Unit::create([
            'property_id' => $property->id, 'room_type_id' => $doubleRoom->id, 'building_id' => $building->id,
            'floor_id' => $floor1->id, 'code' => $code, 'unit_kind' => 'room', 'max_occupancy' => 2,
        ]));
        $aptUnits = collect(['A1', 'A2'])->map(fn (string $code) => Unit::create([
            'property_id' => $property->id, 'room_type_id' => $apartment->id, 'building_id' => $building->id,
            'floor_id' => $floor0->id, 'code' => $code, 'unit_kind' => 'apartment', 'max_occupancy' => 4,
        ]));

        $property->amenities()->attach([$wifi->id, $pool->id]);
        $roomUnits->each(fn (Unit $u) => $u->amenities()->attach($wifi->id));

        // --- Rate plans + calendar (real prices) ---
        $roomRate = RatePlan::create(['property_id' => $property->id, 'room_type_id' => $doubleRoom->id, 'name' => 'Flexible', 'code' => 'FLEX-DBL', 'currency' => 'EUR']);
        $aptRate = RatePlan::create(['property_id' => $property->id, 'room_type_id' => $apartment->id, 'name' => 'Flexible', 'code' => 'FLEX-APT', 'currency' => 'EUR']);
        $doubleRoom->update(['default_rate_plan_id' => $roomRate->id]);
        $apartment->update(['default_rate_plan_id' => $aptRate->id]);

        $this->seedCalendar($roomRate, 10000);
        $this->seedCalendar($aptRate, 18000);

        // --- Availability (computed, not fabricated) ---
        $availability = app(AvailabilityService::class);
        $availability->recompute($doubleRoom->id, self::RANGE_START, self::RANGE_END);
        $availability->recompute($apartment->id, self::RANGE_START, self::RANGE_END);

        // --- Guests ---
        $guest1 = Guest::create(['first_name' => 'Demo', 'last_name' => 'Traveller', 'email' => 'demo.traveller@vyrobel-demo.test', 'phone' => '+351910000001', 'nationality' => 'GB']);
        $guest2 = Guest::create(['first_name' => 'Demo', 'last_name' => 'Walker', 'email' => 'demo.walker@vyrobel-demo.test', 'phone' => '+351910000002', 'nationality' => 'DE']);
        $guest3 = Guest::create(['first_name' => 'Demo', 'last_name' => 'Booker', 'email' => 'demo.booker@vyrobel-demo.test', 'phone' => '+351910000003', 'nationality' => 'FR']);

        $vat = Tax::create(['property_id' => $property->id, 'name' => 'VAT', 'kind' => 'vat', 'mode' => 'percentage', 'rate' => 23.0]);

        // --- Reservations across multiple sources, all through AssignmentService ---
        $this->createDemoStay('direct', $property, $doubleRoom, $roomRate, $roomUnits[0], $guest1, '2026-09-05', '2026-09-08', $vat, fullyPaid: true);
        $walkIn = $this->createDemoStay('walk_in', $property, $apartment, $aptRate, $aptUnits[0], $guest2, '2026-09-06', '2026-09-09', $vat, fullyPaid: false);
        $this->createDemoStay('ota', $property, $doubleRoom, $roomRate, $roomUnits[1], $guest3, '2026-09-10', '2026-09-12', $vat, fullyPaid: true, otaRef: 'OTA-DEMO-0001');

        // Check the walk-in out → real departure-clean task via the checkout event → listener.
        app(CheckOutReservation::class)->handle($walkIn);
    }

    private function seedCalendar(RatePlan $ratePlan, int $priceMinor): void
    {
        $date = CarbonImmutable::parse(self::RANGE_START);
        $end = CarbonImmutable::parse(self::RANGE_END);

        for (; $date->lessThan($end); $date = $date->addDay()) {
            RateCalendar::create([
                'rate_plan_id' => $ratePlan->id,
                'date' => $date->toDateString(),
                'price' => Money::of($priceMinor, 'EUR'),
            ]);
        }
    }

    private function createDemoStay(
        string $source,
        Property $property,
        RoomType $roomType,
        RatePlan $ratePlan,
        Unit $unit,
        Guest $guest,
        string $checkIn,
        string $checkOut,
        Tax $vat,
        bool $fullyPaid,
        ?string $otaRef = null,
    ): Reservation {
        $roomMinor = (int) RateCalendar::query()
            ->where('rate_plan_id', $ratePlan->id)
            ->whereDate('date', '>=', $checkIn)
            ->whereDate('date', '<', $checkOut)
            ->sum('price_minor');

        $reservation = app(AssignmentService::class)->createBooking(
            [
                'property_id' => $property->id, 'currency' => 'EUR',
                'check_in' => $checkIn, 'check_out' => $checkOut,
                'adults' => 2, 'lead_guest_id' => $guest->id,
                'source' => $source, 'ota_reservation_id' => $otaRef,
            ],
            [[
                'room_type_id' => $roomType->id, 'unit_id' => $unit->id, 'rate_plan_id' => $ratePlan->id,
                'check_in' => $checkIn, 'check_out' => $checkOut, 'adults' => 2,
                'price_minor' => $roomMinor, 'currency' => 'EUR',
            ]],
        );

        $folios = app(FolioService::class);
        $folio = $folios->openFolio($reservation);
        $folios->postCharge($folio, 'room', "Room stay {$checkIn} → {$checkOut}", Money::of($roomMinor, 'EUR'));
        $folios->applyTax($folio, $vat, Money::of($roomMinor, 'EUR'));

        $folio->refresh();
        $due = $fullyPaid ? $folio->balance_minor : intdiv($folio->balance_minor, 2);
        if ($due > 0) {
            $folios->recordPayment($folio, Money::of($due, 'EUR'), 'tok_demo_card');
        }

        return $reservation;
    }
}
