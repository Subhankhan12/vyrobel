    /**
     * Seed a few coherent inbox conversations on the MANUAL channel through {@see InboxService} only:
     *   • a pre-arrival question from a real demo guest, LINKED to their real reservation, with an operator
     *     reply (manual channel → delivered);
     *   • an UNLINKED enquiry from a stranger (matcher creates the guest; threads on the participant anchor);
     *   • a RESOLVED (closed) thread with a reply.
     * Inbound via postInbound (real matching + threading), replies via sendOutbound — so the seeded data
     * carries genuine guest/reservation links + delivery states.
     */
    private function seedInbox(User $staff, Guest $guest1, Reservation $stay1, Guest $guest2): void
    {
        $inbox = app(InboxService::class);

        // 1. Pre-arrival question from a KNOWN demo guest, linked to their booking, then an operator reply.
        $arrival = $inbox->postInbound([
            'channel' => 'manual',
            'external_thread_ref' => 'demo-thread-arrival',
            'external_message_id' => 'demo-msg-arrival-1',
            'subject' => 'Early check-in?',
            'body' => 'Hi! We land around 2pm — is an early check-in possible for our stay?',
            'participant_identity' => 'demo.traveller@vyrobel-demo.test',
            'sender_label' => 'Demo Traveller',
            'guest_id' => $guest1->id,          // explicit link to the real demo guest
            'reservation_id' => $stay1->id,     // booking context beside the conversation
        ]);
        $inbox->sendOutbound($arrival->thread, 'Hello! Early check-in from 1pm is usually fine — we’ll have your room ready. Safe travels!', $staff);

        // 2. Unlinked general enquiry from a stranger — the matcher creates the guest; threads on the
        // participant anchor (no booking).
        $inbox->postInbound([
            'channel' => 'manual',
            'external_message_id' => 'demo-msg-enquiry-1',
            'subject' => 'Dogs & parking?',
            'body' => 'Do you allow dogs, and is there parking near the property?',
            'participant_identity' => 'curious.enquirer@example.test',
            'sender_label' => 'Curious Enquirer',
        ]);

        // 3. A resolved conversation from another real demo guest — reply, then close.
        $resolved = $inbox->postInbound([
            'channel' => 'manual',
            'external_thread_ref' => 'demo-thread-resolved',
            'external_message_id' => 'demo-msg-resolved-1',
            'subject' => 'Left a charger',
            'body' => 'Thanks for a lovely stay — I think I left a phone charger in the room.',
            'participant_identity' => 'demo.walker@vyrobel-demo.test',
            'sender_label' => 'Demo Walker',
            'guest_id' => $guest2->id,
        ]);
        $inbox->sendOutbound($resolved->thread, 'Found it! We’ll post it to the address on file today. Thanks for staying with us.', $staff);
        $inbox->close($resolved->thread);
    }

    /**
     * Seed a realistic maintenance spread on the demo units, through {@see MaintenanceService} only:
     *   • OPEN            — an unassigned ticket (room 103, no booking).
     *   • IN PROGRESS     — assigned + started (room 102).
     *   • OUT OF SERVICE  — an urgent ticket that takes room 101 out of service; 101 has an active stay,
     *                       so the work order shows the REAL manual-move flag (1 booking to move).
     *   • RESOLVED · owner cost   — a cost on an OWNER-owned apartment (A2) → a real deductible
     *                               owner_expense via the certified path ("charged to the owner").
     *   • RESOLVED · operator cost — a cost on an operator-owned room (103) → NO owner_expense.
     *
     * @param  Collection<int, Unit>  $roomUnits  operator-owned rooms [101, 102, 103]
     * @param  Collection<int, Unit>  $aptUnits  owner-owned apartments [A1, A2]
     */
    private function seedMaintenance(Collection $roomUnits, Collection $aptUnits, User $staff): void
    {
        $maintenance = app(MaintenanceService::class);

        // OPEN — a straightforward unassigned ticket on a room with no booking.
        $maintenance->open([
            'unit_id' => $roomUnits[2]->id, 'title' => 'Wardrobe door off its runner',
            'description' => 'Sliding wardrobe door has come off the bottom runner — needs refitting.',
            'category' => 'other', 'priority' => 'normal', 'reported_by' => $staff->id,
        ]);

        // IN PROGRESS — assigned to the demo technician and started.
        $inProgress = $maintenance->open([
            'unit_id' => $roomUnits[1]->id, 'title' => 'Air-con intermittently cutting out',
            'description' => 'Guest reports the split unit stops after ~20 minutes. Suspect a faulty thermostat.',
            'category' => 'appliance', 'priority' => 'high', 'reported_by' => $staff->id,
        ]);
        $maintenance->assign($inProgress->refresh(), $staff->id);
        $maintenance->start($inProgress->refresh());

        // OUT OF SERVICE — an urgent ticket that blocks room 101 (which has an active stay) from sale.
        $oos = $maintenance->open([
            'unit_id' => $roomUnits[0]->id, 'title' => 'Burst pipe under bathroom sink',
            'description' => 'Water damage under the vanity; isolation valve shut. Room not lettable until fixed.',
            'category' => 'plumbing', 'priority' => 'urgent', 'takes_out_of_service' => true, 'reported_by' => $staff->id,
        ]);
        $maintenance->assign($oos->refresh(), $staff->id);
        $maintenance->start($oos->refresh());

        // RESOLVED · owner cost — on an OWNER-owned apartment → a real deductible owner_expense.
        $ownerCost = $maintenance->open([
            'unit_id' => $aptUnits[1]->id, 'title' => 'Dishwasher pump replacement',
            'description' => 'Integrated dishwasher not draining; drain pump replaced.',
            'category' => 'appliance', 'priority' => 'normal', 'reported_by' => $staff->id,
        ]);
        $maintenance->start($ownerCost->refresh());
        $maintenance->resolve($ownerCost->refresh(), Money::of(18000, 'EUR'));

        // RESOLVED · operator cost — on an operator-owned room → NO owner_expense.
        $operatorCost = $maintenance->open([
            'unit_id' => $roomUnits[2]->id, 'title' => 'Repaint scuffed hallway wall',
            'description' => 'Touch-up paint on the corridor wall outside the room.',
            'category' => 'structural', 'priority' => 'low', 'reported_by' => $staff->id,
        ]);
        $maintenance->start($operatorCost->refresh());
        $maintenance->resolve($operatorCost->refresh(), Money::of(4500, 'EUR'));
    }

    /**
     * Make the demo login a real property OWNER (of the apartments) with a governing agreement, then
     * run the certified owner-accounting chain over the apartment bookings so the owner portal shows
     * real earnings/statement/payout — not a fail-closed empty portal.
     *
     * @param  Collection<int, Unit>  $aptUnits
     */
    private function seedOwnerAccounting(
        User $user,
        Property $property,
        RoomType $apartment,
        RatePlan $aptRate,
        Collection $aptUnits,
        Tax $vat,
        Reservation $walkIn,
    ): void {
        // The owner PARTY, linked to the login (owners.user_id) so SetOwnerScopeForPortal resolves it.
        $ownerParty = Owner::create([
            'type' => 'individual',
            'name' => 'Demo Owner',
            'email' => 'demo-owner@vyrobel-demo.test',
            'payout_currency' => 'EUR',
            'user_id' => $user->id,
            'status' => 'active',
        ]);

        // The owner owns the two apartments; the hotel rooms stay operator-owned.
        $aptUnits->each(fn (Unit $u) => $u->update(['owner_id' => $ownerParty->id]));

        // A real, open-ended management agreement (18% commission, owner-wide).
        ManagementAgreement::create([
            'owner_id' => $ownerParty->id,
            'unit_id' => null,
            'commission_pct' => 18.00,
            'payout_currency' => 'EUR',
            'payout_schedule' => 'monthly',
            'effective_from' => '2026-01-01',
            'effective_to' => null,
            'status' => 'active',
        ]);

        // A second apartment stay so the statement aggregates more than one booking (real, via services).
        $aptGuest = Guest::create(['first_name' => 'Demo', 'last_name' => 'Resident', 'email' => 'demo.resident@vyrobel-demo.test', 'phone' => '+351910000004', 'nationality' => 'IE']);
        $aptStay = $this->createDemoStay('direct', $property, $apartment, $aptRate, $aptUnits[1], $aptGuest, '2026-09-14', '2026-09-17', $vat, fullyPaid: true);

        // Attribute the owner's bookings → immutable owner_ledger (derived, read-only over folios).
        $attribution = app(OwnerAttributionService::class);
        $attribution->attributeReservation($walkIn);
        $attribution->attributeReservation($aptStay);

        // September statement = pure projection of the ledger; finalize (locks), then create the payout,
        // left PENDING — the common "statement finalized, payout not yet sent" state the portal showcases.
        $statements = app(OwnerStatementService::class);
        $draft = $statements->generateDraft($ownerParty->id, '2026-09-01', '2026-09-30');
        $finalized = $statements->finalize($draft);
        app(OwnerPayoutService::class)->createFromStatement($finalized);
    }

    /**
     * Attach N real demo photos to a room-type on the `public` disk (first = cover). Files are generated
     * locally with GD — actual viewable bytes, never a hotlinked or fabricated URL.
     *
     * @param  array{0:array{0:int,1:int,2:int},1:array{0:int,1:int,2:int}}  $palette  [top RGB, bottom RGB]
     */
    private function seedPhotos(RoomType $roomType, string $label, array $palette, int $count): void
    {
        for ($i = 0; $i < $count; $i++) {
            $bytes = PlaceholderImage::jpeg($label, 'Vyrobel Demo - photo '.($i + 1), $palette[0], $palette[1]);
            $path = 'demo-photos/'.$roomType->code.'-'.($i + 1).'.jpg';
            Storage::disk('public')->put($path, $bytes);

            Media::create([
                'mediable_type' => $roomType->getMorphClass(),
                'mediable_id' => $roomType->getKey(),
                'collection' => 'photos',
                'disk' => 'public',
                'path' => $path,
                'mime' => 'image/jpeg',
                'size' => strlen($bytes),
                'sort_order' => $i,
                'is_cover' => $i === 0,
                'alt' => $label.' — demo photo '.($i + 1),
            ]);
        }
    }

    private function seedCalendar(RatePlan $ratePlan, int $priceMinor): void
    {
        $date = CarbonImmutable::parse(self::RANGE_START);
        $end = CarbonImmutable::parse(self::RANGE_END);

        for (; $date->lessThan($end); $date = $date->addDay()) {
            RateCalendar::create([
                'rate_plan_id' => $ratePlan->id,
                'date' => $date->toDateString(),
                'price' => Money::of($priceMinor, 'EUR'),
            ]);
        }
    }

    private function createDemoStay(
        string $source,
        Property $property,
        RoomType $roomType,
        RatePlan $ratePlan,
        Unit $unit,
        Guest $guest,
        string $checkIn,
        string $checkOut,
        Tax $vat,
        bool $fullyPaid,
        ?string $otaRef = null,
    ): Reservation {
        $roomMinor = (int) RateCalendar::query()
            ->where('rate_plan_id', $ratePlan->id)
            ->whereDate('date', '>=', $checkIn)
            ->whereDate('date', '<', $checkOut)
            ->sum('price_minor');

        $reservation = app(AssignmentService::class)->createBooking(
            [
                'property_id' => $property->id, 'currency' => 'EUR',
                'check_in' => $checkIn, 'check_out' => $checkOut,
                'adults' => 2, 'lead_guest_id' => $guest->id,
                'source' => $source, 'ota_reservation_id' => $otaRef,
            ],
            [[
                'room_type_id' => $roomType->id, 'unit_id' => $unit->id, 'rate_plan_id' => $ratePlan->id,
                'check_in' => $checkIn, 'check_out' => $checkOut, 'adults' => 2,
                'price_minor' => $roomMinor, 'currency' => 'EUR',
            ]],
        );

        $folios = app(FolioService::class);
        $folio = $folios->openFolio($reservation);
        $folios->postCharge($folio, 'room', "Room stay {$checkIn} → {$checkOut}", Money::of($roomMinor, 'EUR'));
        $folios->applyTax($folio, $vat, Money::of($roomMinor, 'EUR'));

        $folio->refresh();
        $due = $fullyPaid ? $folio->balance_minor : intdiv($folio->balance_minor, 2);
        if ($due > 0) {
            $folios->recordPayment($folio, Money::of($due, 'EUR'), 'tok_demo_card');
        }

        return $reservation;
    }
