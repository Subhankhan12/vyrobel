    private function seedCalendar(RatePlan $ratePlan, int $priceMinor): void
    {
        $this->seedCalendarRange($ratePlan, $priceMinor, $this->rangeStart(), $this->rangeEnd());
    }

    private function seedCalendarRange(RatePlan $ratePlan, int $priceMinor, string $start, string $end): void
    {
        $date = CarbonImmutable::parse($start);
        $endDate = CarbonImmutable::parse($end);

        for (; $date->lessThan($endDate); $date = $date->addDay()) {
            // updateOrCreate (not create) so overlapping seed windows — the rolling
            // window below overlaps the near-term stay's own range — never collide on
            // the unique (rate_plan_id, date) index. Seed-only, idempotent.
            RateCalendar::updateOrCreate(
                ['rate_plan_id' => $ratePlan->id, 'date' => $date->toDateString()],
                ['price' => Money::of($priceMinor, 'EUR')],
            );
        }
    }

    /**
     * DEMO ANALYTICS HISTORY (Batch B) — a deterministic spread of past-created bookings so Insights renders
     * a real, meaningful lead-time distribution + day-of-week occupancy on the demo. Each stay is a REAL
     * booking through the certified AssignmentService (no double-booking); the ONLY demo affordance is
     * backdating `created_at` to a realistic lead before check-in (production has genuine timestamps). Owner
     * (apartment) stays are attributed so the owner ledger stays consistent with the owner-scoped metrics. A
     * collision with an existing demo stay on a unit is skipped, so the rest still populate the shape.
     *
     * @param  list<Unit>  $roomUnits
     * @param  list<Unit>  $aptUnits
     */
    private function seedAnalyticsHistory(
        Property $property,
        RoomType $doubleRoom,
        RoomType $apartment,
        RatePlan $roomRate,
        RatePlan $aptRate,
        array $roomUnits,
        array $aptUnits,
        Guest $guest,
        AvailabilityService $availability,
    ): void {
        $today = CarbonImmutable::today();

        // Each row: type (dbl|apt) · unit index · check-in offset (days) · nights · lead days · source. Offsets
        // keep created_at ≤ today (offset ≤ lead) and cover all four lead buckets + a weekday spread; per
        // (type,unit) they never overlap. Sources use only the real `reservations.source` enum.
        $row = fn (string $type, int $unit, int $in, int $nights, int $lead, string $source): array => compact('type', 'unit', 'in', 'nights', 'lead', 'source');
        $schedule = [
            $row('dbl', 0, 2, 2, 4, 'direct'),    $row('dbl', 1, 4, 2, 5, 'ota'),       $row('apt', 0, 3, 2, 6, 'direct'),
            $row('dbl', 0, 16, 3, 18, 'ota'),     $row('dbl', 1, 20, 2, 21, 'direct'),  $row('apt', 1, 18, 2, 14, 'corporate'),
            $row('dbl', 2, 8, 2, 9, 'direct'),    $row('dbl', 2, 33, 2, 36, 'ota'),     $row('apt', 0, 24, 2, 26, 'direct'),
            $row('dbl', 0, 52, 2, 60, 'direct'),  $row('dbl', 1, 61, 3, 70, 'ota'),     $row('apt', 1, 55, 2, 62, 'direct'),
            $row('dbl', 2, 78, 3, 88, 'direct'),  $row('dbl', 0, 96, 2, 110, 'ota'),    $row('apt', 0, 66, 2, 74, 'corporate'),
            $row('dbl', 1, 116, 3, 130, 'direct'), $row('dbl', 2, 132, 2, 150, 'ota'),  $row('apt', 1, 124, 2, 128, 'ota'),
        ];

        foreach ($schedule as $entry) {
            $typeKey = $entry['type'];
            $idx = $entry['unit'];
            $offset = $entry['in'];
            $nights = $entry['nights'];
            $lead = $entry['lead'];
            $source = $entry['source'];
            $roomType = $typeKey === 'dbl' ? $doubleRoom : $apartment;
            $ratePlan = $typeKey === 'dbl' ? $roomRate : $aptRate;
            $units = $typeKey === 'dbl' ? $roomUnits : $aptUnits;
            if (! isset($units[$idx])) {
                continue;
            }

            $checkIn = $today->addDays($offset);
            $checkOut = $checkIn->addDays($nights);
            $this->seedCalendarRange($ratePlan, $typeKey === 'dbl' ? 10000 : 14000, $checkIn->toDateString(), $checkOut->toDateString());
            $availability->recompute($roomType->id, $checkIn->toDateString(), $checkOut->toDateString());

            try {
                $roomMinor = (int) RateCalendar::query()
                    ->where('rate_plan_id', $ratePlan->id)
                    ->whereDate('date', '>=', $checkIn->toDateString())
                    ->whereDate('date', '<', $checkOut->toDateString())
                    ->sum('price_minor');

                $reservation = app(AssignmentService::class)->createBooking(
                    ['property_id' => $property->id, 'currency' => 'EUR', 'check_in' => $checkIn->toDateString(), 'check_out' => $checkOut->toDateString(), 'adults' => 2, 'lead_guest_id' => $guest->id, 'source' => $source],
                    [['room_type_id' => $roomType->id, 'unit_id' => $units[$idx]->id, 'rate_plan_id' => $ratePlan->id, 'check_in' => $checkIn->toDateString(), 'check_out' => $checkOut->toDateString(), 'adults' => 2, 'price_minor' => $roomMinor, 'currency' => 'EUR']],
                );

                // DEMO-ONLY: backdate created_at to a realistic lead before check-in (raw update → no timestamp magic).
                DB::table('reservations')->where('id', $reservation->id)->update(['created_at' => $checkIn->subDays($lead)->toDateTimeString()]);

                // Owner (apartment) stays attribute to the owner ledger, so owner earnings stay consistent.
                if ($typeKey === 'apt') {
                    app(OwnerAttributionService::class)->attributeReservation($reservation);
                }
            } catch (\Throwable) {
                continue;   // a collision with an existing demo stay on this unit — skip, keep the rest
            }
        }

        // PRIOR-YEAR occupancy (GATE 4) — a handful of REAL apartment stays ~one year back, so the owner Insights
        // "vs last year" occupancy delta has genuine prior-year data to compare against (never a fabricated delta,
        // #39). DELIBERATELY NOT ATTRIBUTED to the owner ledger: occupancy is computed from reservation_units, so
        // these give real prior-year occupancy WITHOUT adding 2025 ledger entries that would move the demo Balance.
        // Apartment (owner) units only, in the same months as this year's forward apt stays (Aug–Nov).
        $priorYear = [
            [0, -353, 2], [1, -327, 3], [0, -292, 2], [1, -262, 2],
        ];
        foreach ($priorYear as [$idx, $offset, $nights]) {
            if (! isset($aptUnits[$idx])) {
                continue;
            }
            $checkIn = $today->addDays($offset);
            $checkOut = $checkIn->addDays($nights);
            $this->seedCalendarRange($aptRate, 14000, $checkIn->toDateString(), $checkOut->toDateString());
            $availability->recompute($apartment->id, $checkIn->toDateString(), $checkOut->toDateString());

            try {
                $roomMinor = (int) RateCalendar::query()
                    ->where('rate_plan_id', $aptRate->id)
                    ->whereDate('date', '>=', $checkIn->toDateString())
                    ->whereDate('date', '<', $checkOut->toDateString())
                    ->sum('price_minor');

                app(AssignmentService::class)->createBooking(
                    ['property_id' => $property->id, 'currency' => 'EUR', 'check_in' => $checkIn->toDateString(), 'check_out' => $checkOut->toDateString(), 'adults' => 2, 'lead_guest_id' => $guest->id, 'source' => 'direct'],
                    [['room_type_id' => $apartment->id, 'unit_id' => $aptUnits[$idx]->id, 'rate_plan_id' => $aptRate->id, 'check_in' => $checkIn->toDateString(), 'check_out' => $checkOut->toDateString(), 'adults' => 2, 'price_minor' => $roomMinor, 'currency' => 'EUR']],
                );
                // NO OwnerAttributionService call — see the note above (keeps the demo Balance/statements unchanged).
            } catch (\Throwable) {
                continue;
            }
        }
    }

    private function createDemoStay(
        string $source,
        Property $property,
        RoomType $roomType,
        RatePlan $ratePlan,
        Unit $unit,
        Guest $guest,
        string $checkIn,
        string $checkOut,
        Tax $vat,
        bool $fullyPaid,
        ?string $otaRef = null,
    ): Reservation {
        $roomMinor = (int) RateCalendar::query()
            ->where('rate_plan_id', $ratePlan->id)
            ->whereDate('date', '>=', $checkIn)
            ->whereDate('date', '<', $checkOut)
            ->sum('price_minor');

        $reservation = app(AssignmentService::class)->createBooking(
            [
                'property_id' => $property->id, 'currency' => 'EUR',
                'check_in' => $checkIn, 'check_out' => $checkOut,
                'adults' => 2, 'lead_guest_id' => $guest->id,
                'source' => $source, 'ota_reservation_id' => $otaRef,
            ],
            [[
                'room_type_id' => $roomType->id, 'unit_id' => $unit->id, 'rate_plan_id' => $ratePlan->id,
                'check_in' => $checkIn, 'check_out' => $checkOut, 'adults' => 2,
                'price_minor' => $roomMinor, 'currency' => 'EUR',
            ]],
        );

        $folios = app(FolioService::class);
        $folio = $folios->openFolio($reservation);
        $folios->postCharge($folio, 'room', "Room stay {$checkIn} → {$checkOut}", Money::of($roomMinor, 'EUR'));
        $folios->applyTax($folio, $vat, Money::of($roomMinor, 'EUR'));

        $folio->refresh();
        $due = $fullyPaid ? $folio->balance_minor : intdiv($folio->balance_minor, 2);
        if ($due > 0) {
            $folios->recordPayment($folio, Money::of($due, 'EUR'), 'tok_demo_card');
        }

        return $reservation;
    }
