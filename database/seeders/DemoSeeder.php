/**
 * ONE realistic demo organization with a MIXED property (hotel room types AND apartment units).
 *
 * Everything is unmistakably DEMO (names + the `vyrobel-demo` slug) — never presented as real.
 * Nothing is fabricated: availability is computed by AvailabilityService, `sold` comes from real
 * bookings through AssignmentService, folio totals come from the FolioService ledger, and the
 * departure task is generated by the real checkout event → listener chain.
 */
class DemoSeeder extends Seeder
{
    /**
     * The demo bookable window. A ROLLING window anchored at "today" (not a fixed Sept band) so the
     * public storefront demos real availability year-round — a guest searching any normal upcoming date
     * sees rooms, not "0 rooms available". today → +180d comfortably spans the fixed Sept demo stays.
     * Both the rate calendar and the computed availability use this one window.
     */
    private function rangeStart(): string
    {
        return CarbonImmutable::today()->toDateString();
    }

    private function rangeEnd(): string
    {
        return CarbonImmutable::today()->addDays(180)->toDateString();
    }

    public function run(): void
    {
        $tenant = app(TenantContext::class);

        $org = $tenant->runAsSuperAdmin(fn () => Organization::firstOrCreate(
            ['slug' => 'vyrobel-demo'],
            [
                'name' => 'Vyrobel Demo — Seaside Hotel & Apartments',
                'mode' => 'chain',
                'default_currency' => 'EUR',
                'default_locale' => 'en',
                'country' => 'PT',
                'status' => 'active',
                'billing_email' => 'billing@vyrobel-demo.test',
                // DEMO ONLY — the managing agent's registered identity, so the owner Booking-Summary PDF
                // letterhead (real billing_company + VAT + country) renders on a fresh demo. Clearly demo data.
                'billing_company' => 'Vyrobel Demo Hospitality, Lda',
                'billing_vat_id' => 'PT 512 034 776',
            ],
        ));

        app(OrganizationRoleProvisioner::class)->provision($org);

        $tenant->forOrganization($org->id, fn () => $this->buildDemo($org));
    }

    private function buildDemo(Organization $org): void
    {
        $owner = User::firstOrCreate(
            ['email' => 'demo-owner@vyrobel-demo.test'],
            ['name' => 'Demo Owner', 'password' => Hash::make('password'), 'status' => 'active'],
        );
        Membership::firstOrCreate(
            ['organization_id' => $org->id, 'user_id' => $owner->id],
            ['status' => 'active', 'invited_at' => now()],
        );
        app(PermissionRegistrar::class)->setPermissionsTeamId($org->id);

        // The demo owner is a UNIT OWNER — exactly what OwnerInviteService's owner path now produces:
        // an active Membership (the only way their org resolves) + the owner-only `External Owner` role
        // (`owner_portal.view` and nothing else). NOT `Property Owner`: despite the name, that is the ORG
        // ADMIN (`['*']` — all 44 permissions). This seeder used to grant it, which handed the demo owner
        // payments.refund/guests.erase/users.manage and, before the back-office gate, the entire operator
        // app. The demo must model production, or the security gate is not what the demo journeys prove.
        $owner->syncRoles(['External Owner']);

        // A staff/operator login so BOTH role journeys are demoable via the real login. A Membership alone
        // is NOT operator access (an owner has one too — that was the hole): staff need a real back-office
        // role, as a real staff invite assigns. Hotel Manager mirrors OwnerInviteService's 'manager' slug.
        $staff = User::firstOrCreate(
            ['email' => 'demo-staff@vyrobel-demo.test'],
            ['name' => 'Demo Staff', 'password' => Hash::make('password'), 'status' => 'active'],
        );
        Membership::firstOrCreate(
            ['organization_id' => $org->id, 'user_id' => $staff->id],
            ['status' => 'active', 'invited_at' => now()],
        );
        $staff->syncRoles(['Hotel Manager']);

        // A SECOND staff login, deliberately — so the demo DEMONSTRATES the separation of duties rather than
        // hitting a wall (2026-07-17). The catalog withholds `payments.refund` and `payouts.manage` from
        // Hotel Manager: handing money back to a guest, or remitting an owner, is an accounting act. Now that
        // those routes are actually enforced (invariant #30), `demo-staff` correctly sees no refund button and
        // no payout controls — which reads as a BUG unless the demo can also show the other side of the line.
        //
        // Two accounts, one point: the control is real, and the right person can still do the work.
        //   demo-staff@…      Hotel Manager → runs the house; cannot refund or pay out
        //   demo-accountant@… Accountant    → refunds + runs the payout run
        //
        // (The alternative — granting demo-staff a role that can do everything — is how the #26 audit's
        // inverted seeder happened: a seeder that disagrees with the production model teaches the wrong thing.)
        $accountant = User::firstOrCreate(
            ['email' => 'demo-accountant@vyrobel-demo.test'],
            ['name' => 'Demo Accountant', 'password' => Hash::make('password'), 'status' => 'active'],
        );
        Membership::firstOrCreate(
            ['organization_id' => $org->id, 'user_id' => $accountant->id],
            ['status' => 'active', 'invited_at' => now()],
        );
        $accountant->syncRoles(['Accountant']);

        // The ORG ADMIN. ⚠️ Added because enforcing `users.manage` (invariant #30) otherwise LEFT THE INVITE
        // FLOW UNDEMOABLE: `demo-staff` could invite an owner before only because nothing checked, and
        // neither Hotel Manager nor Accountant holds `users.manage` — so with the gate on, NO demo account
        // could reach a real shipped feature. Caught by seeding and looking, not by a test.
        //
        // ⚠️ `Property Owner` is the ORG ADMIN (`['*']`), NOT the unit owner — the naming trap the #26 audit
        // found the demo seeder falling into. The unit owner is `demo-owner` (External Owner) below.
        //
        // The four accounts now mirror the production model exactly, and together they demo the whole RBAC
        // story rather than one all-powerful login:
        //   demo-admin@…      Property Owner  → org admin: invites staff/owners, can do anything
        //   demo-accountant@… Accountant      → refunds + runs the payout run
        //   demo-staff@…      Hotel Manager   → runs the house; NO refund, NO payout, NO invite
        //   demo-owner@…      External Owner  → /owner only; refused from /app entirely (#26)
        $admin = User::firstOrCreate(
            ['email' => 'demo-admin@vyrobel-demo.test'],
            ['name' => 'Demo Admin', 'password' => Hash::make('password'), 'status' => 'active'],
        );
        Membership::firstOrCreate(
            ['organization_id' => $org->id, 'user_id' => $admin->id],
            ['status' => 'active', 'invited_at' => now()],
        );
        $admin->syncRoles(['Property Owner']);

        // Batch C · GATE 1 — a real HOUSEKEEPER so the Housekeeping board's assign picker is populated (the
        // assignable set is the Housekeeping dept via StaffRoster). demo-housekeeper@… holds the `Housekeeping`
        // role — a genuine demo staff member, like every row here (never a fabricated assignee).
        $housekeeper = User::firstOrCreate(
            ['email' => 'demo-housekeeper@vyrobel-demo.test'],
            ['name' => 'Rosa Fernandes', 'password' => Hash::make('password'), 'status' => 'active'],
        );
        Membership::firstOrCreate(
            ['organization_id' => $org->id, 'user_id' => $housekeeper->id],
            ['status' => 'active', 'invited_at' => now()],
        );
        $housekeeper->syncRoles(['Housekeeping']);

        // --- Mixed property ---
        $property = Property::create([
            'name' => 'Demo Seaside Property', 'brand' => 'Vyrobel Demo', 'type' => 'mixed',
            // Public booking-engine identifier: the `/book/{slug}` storefront resolves the property by
            // this slug. Without it the public booking loop is unreachable for the demo data.
            'slug' => 'seaside-demo',
            'currency' => 'EUR', 'timezone' => 'Europe/Lisbon',
            'check_in_time' => '15:00:00', 'check_out_time' => '11:00:00', 'status' => 'active',
        ]);
        PropertyPolicy::create([
            'property_id' => $property->id,
            'cancellation' => ['type' => 'flexible', 'free_until_days' => 2],
            'pet' => 'on_request', 'smoking' => 'not_allowed', 'min_stay' => 1, 'max_stay' => 30,
        ]);
        $building = Building::create(['property_id' => $property->id, 'name' => 'Main Building', 'code' => 'MB']);
        $floor0 = Floor::create(['building_id' => $building->id, 'level' => 0, 'name' => 'Ground']);
        $floor1 = Floor::create(['building_id' => $building->id, 'level' => 1, 'name' => 'First']);

        $wifi = Amenity::firstOrCreate(['name' => 'WiFi'], ['icon' => 'wifi', 'category' => 'connectivity']);
        $pool = Amenity::firstOrCreate(['name' => 'Pool'], ['icon' => 'pool', 'category' => 'leisure']);
        // The `amenities` table is a GLOBAL shared reference catalog (reused across tenants, no organization_id) —
        // seeding a common real vocabulary here is reference data, not fabricated business data. It gives the owner
        // Add-Unit wizard's amenity chips a usable set; the `icon` slug is mapped to an SVG in the view.
        foreach ([
            ['Kitchen', 'kitchen', 'cooking'],
            ['Air conditioning', 'ac', 'climate'],
            ['Heating', 'heating', 'climate'],
            ['Free parking', 'parking', 'parking'],
            ['Washer', 'washer', 'laundry'],
            ['TV', 'tv', 'entertainment'],
            ['Balcony', 'balcony', 'outdoor'],
            ['Pet-friendly', 'pets', 'policy'],
        ] as [$name, $icon, $category]) {
            Amenity::firstOrCreate(['name' => $name], ['icon' => $icon, 'category' => $category]);
        }

        // Hotel room type + apartment unit type under ONE property.
        $doubleRoom = RoomType::create([
            'property_id' => $property->id, 'name' => 'Double Room', 'code' => 'DBL', 'kind' => 'room',
            'std_occupancy' => 2, 'max_adults' => 2, 'max_children' => 1,
        ]);
        $apartment = RoomType::create([
            'property_id' => $property->id, 'name' => 'One-Bedroom Apartment', 'code' => 'APT', 'kind' => 'apartment',
            'std_occupancy' => 3, 'max_adults' => 3, 'max_children' => 2, 'bedrooms' => 1,
        ]);

        $roomUnits = collect(['101', '102', '103'])->map(fn (string $code) => Unit::create([
            'property_id' => $property->id, 'room_type_id' => $doubleRoom->id, 'building_id' => $building->id,
            'floor_id' => $floor1->id, 'code' => $code, 'unit_kind' => 'room', 'max_occupancy' => 2,
        ]));
        $aptUnits = collect(['A1', 'A2'])->map(fn (string $code) => Unit::create([
            'property_id' => $property->id, 'room_type_id' => $apartment->id, 'building_id' => $building->id,
            'floor_id' => $floor0->id, 'code' => $code, 'unit_kind' => 'apartment', 'max_occupancy' => 4,
        ]));

        $property->amenities()->attach([$wifi->id, $pool->id]);
        $roomUnits->each(fn (Unit $u) => $u->amenities()->attach($wifi->id));

        // Arrival info (Phase 4b · SG4) — DEMO door codes + wifi so the guest Arrival Info screen shows a real,
        // released pack. door_code/wifi_password are encrypted at rest; they surface only for the owning guest,
        // and only inside the arrival window (ArrivalPack). Demo values, flagged demo by living in this seeder.
        $roomUnits->each(fn (Unit $u) => $u->update([
            'door_code' => match ($u->code) {
                '101' => '4021', '102' => '7788', default => '5390'
            },
            'wifi_ssid' => 'Seaside-Guest',
            'wifi_password' => 'welcome2026',
            'arrival_notes' => 'Main entrance on Rua do Mar — your room is on the first floor, up the stairs and to the right.',
        ]));
        $aptUnits->each(fn (Unit $u) => $u->update([
            'door_code' => match ($u->code) {
                'A1' => '9145', default => '6273'
            },
            'wifi_ssid' => 'Seaside-Apartments',
            'wifi_password' => 'welcome2026',
            'arrival_notes' => 'Ground-floor apartments — enter through the courtyard gate; your door is signposted.',
        ]));

        // DEMO photos — real, viewable JPEGs generated locally (never hotlinked/fabricated), so the
        // storefront + unit cards look populated. Production photos are real operator uploads.
        $this->seedPhotos($doubleRoom, 'Double Room', [[232, 112, 58], [194, 65, 12]], 3);
        $this->seedPhotos($apartment, 'One-Bedroom Apartment', [[224, 146, 30], [178, 106, 8]], 3);

        // --- Rate plans + calendar (real prices) ---
        $roomRate = RatePlan::create(['property_id' => $property->id, 'room_type_id' => $doubleRoom->id, 'name' => 'Flexible', 'code' => 'FLEX-DBL', 'currency' => 'EUR']);
        $aptRate = RatePlan::create(['property_id' => $property->id, 'room_type_id' => $apartment->id, 'name' => 'Flexible', 'code' => 'FLEX-APT', 'currency' => 'EUR']);
        $doubleRoom->update(['default_rate_plan_id' => $roomRate->id]);
        $apartment->update(['default_rate_plan_id' => $aptRate->id]);

        $this->seedCalendar($roomRate, 10000);
        $this->seedCalendar($aptRate, 18000);

        // --- Availability (computed, not fabricated) ---
        $availability = app(AvailabilityService::class);
        $availability->recompute($doubleRoom->id, $this->rangeStart(), $this->rangeEnd());
        $availability->recompute($apartment->id, $this->rangeStart(), $this->rangeEnd());

        // --- Guests ---
        // `is_vip` / `risk_flag` are REAL columns and `tags` is a REAL per-tenant catalog on the shared
        // polymorphic pivot — but nothing in the app has ever written any of the three, so the Guests CRM
        // would demo them as permanently empty. Seeded here (demo data, like every guest on this row) so the
        // styled list shows the true feature. The guest PROFILE is where they become editable (Wave 2 ·
        // Sub-gate 5); until then this is the only writer.
        $guest1 = Guest::create(['first_name' => 'Demo', 'last_name' => 'Traveller', 'email' => 'demo.traveller@vyrobel-demo.test', 'phone' => '+351910000001', 'nationality' => 'GB', 'is_vip' => true]);
        $guest2 = Guest::create(['first_name' => 'Demo', 'last_name' => 'Walker', 'email' => 'demo.walker@vyrobel-demo.test', 'phone' => '+351910000002', 'nationality' => 'DE', 'risk_flag' => true]);
        $guest3 = Guest::create(['first_name' => 'Demo', 'last_name' => 'Booker', 'email' => 'demo.booker@vyrobel-demo.test', 'phone' => '+351910000003', 'nationality' => 'FR']);

        $repeatTag = Tag::create(['name' => 'Repeat', 'color' => '#B4822C']);
        $corporateTag = Tag::create(['name' => 'Corporate', 'color' => '#8A6410']);
        $guest1->tags()->attach($repeatTag);
        $guest3->tags()->attach($corporateTag);

        $vat = Tax::create(['property_id' => $property->id, 'name' => 'VAT', 'kind' => 'vat', 'mode' => 'percentage', 'rate' => 23.0]);

        // --- Reservations across multiple sources, all through AssignmentService ---
        $stay1 = $this->createDemoStay('direct', $property, $doubleRoom, $roomRate, $roomUnits[0], $guest1, '2026-09-05', '2026-09-08', $vat, fullyPaid: true);
        $walkIn = $this->createDemoStay('walk_in', $property, $apartment, $aptRate, $aptUnits[0], $guest2, '2026-09-06', '2026-09-09', $vat, fullyPaid: false);
        $this->createDemoStay('ota', $property, $doubleRoom, $roomRate, $roomUnits[1], $guest3, '2026-09-10', '2026-09-12', $vat, fullyPaid: true, otaRef: 'OTA-DEMO-0001');

        // Phase 4b · SG4 — a NEAR-TERM stay for guest1 (arrives tomorrow), so the guest Arrival Info screen
        // demos a RELEASED pack (door code + wifi visible, since it's inside the arrival window) alongside the
        // far Sep stay whose code is still withheld. Priced + made available over just these dates.
        $soonIn = CarbonImmutable::today()->addDay();
        $soonOut = $soonIn->addDays(3);
        $this->seedCalendarRange($roomRate, 10000, $soonIn->toDateString(), $soonOut->toDateString());
        $availability->recompute($doubleRoom->id, $soonIn->toDateString(), $soonOut->toDateString());
        // Half-paid so it carries a real balance — the guest can apply wallet credit to it (Phase 4c · SG2).
        $this->createDemoStay('direct', $property, $doubleRoom, $roomRate, $roomUnits[2], $guest1, $soonIn->toDateString(), $soonOut->toDateString(), $vat, fullyPaid: false);

        // Phase 5 — a PAST, checked-out stay for guest1 so the review flow is demoable (and the checkout fires the
        // real Review Request email → Mailpit). Priced + available over just these past dates.
        $pastIn = CarbonImmutable::today()->subDays(14);
        $pastOut = $pastIn->addDays(3);
        $this->seedCalendarRange($roomRate, 10000, $pastIn->toDateString(), $pastOut->toDateString());
        $availability->recompute($doubleRoom->id, $pastIn->toDateString(), $pastOut->toDateString());
        $pastStay = $this->createDemoStay('direct', $property, $doubleRoom, $roomRate, $roomUnits[1], $guest1, $pastIn->toDateString(), $pastOut->toDateString(), $vat, fullyPaid: true);
        app(CheckOutReservation::class)->handle($pastStay);

        // Batch B — DEMO ANALYTICS DATA (clearly demo, like every row here): a spread of PAST-CREATED bookings
        // so the operator + owner Insights render a MEANINGFUL, REAL lead-time distribution + day-of-week
        // occupancy on the demo. The RUNTIME computes the real aggregate from these real created_at → check_in
        // values (a production install has genuine timestamps); this seed only supplies realistic ones. NOT
        // production data. Deterministic (no rand) → `migrate:fresh --seed` stays reproducible.
        $this->seedAnalyticsHistory($property, $doubleRoom, $apartment, $roomRate, $aptRate, $roomUnits->all(), $aptUnits->all(), $guest3, $availability);

        // Phase 4a — a CLAIMED guest PORTAL account so the guest portal has a real demo login. guest1 (Demo
        // Traveller) leads stay1 above, so this is a genuine BOOKING-TIED account: demo.traveller@vyrobel-demo.test
        // / password. (The 'hashed' cast hashes the plaintext; the saving() hook stamps its blind index.)
        $guest1->forceFill(['password' => 'password', 'email_verified_at' => now()])->save();

        // Phase 4c · SG2 — DEMO wallet credits + a promo code so the guest Wallet has a real, spendable balance
        // (appended through the certified GuestWalletService — never a raw balance). Clearly demo, like every row.
        $wallet = app(GuestWalletService::class);
        $wallet->credit($guest1, GuestCreditEntry::TYPE_REFUND, 'Goodwill refund credit', Money::of(2500, 'EUR'));
        $wallet->credit($guest1, GuestCreditEntry::TYPE_BIRTHDAY, 'Birthday credit', Money::of(1000, 'EUR'), expiresAt: CarbonImmutable::now()->addDays(60));
        PromoCode::create(['code' => 'WELCOME10', 'amount_minor' => 1000, 'currency' => 'EUR', 'description' => 'Welcome credit', 'max_redemptions' => 100, 'is_active' => true]);

        // Phase 4c · SG4 — DEMO saved lists (through the real GuestWishlistService) so the Saved page shows a
        // wishlist + a waitlist. Demo data, like every guest row here.
        $saved = app(GuestWishlistService::class);
        $saved->saveRoom($guest1, $apartment);
        $saved->joinWaitlist($guest1, $doubleRoom, ['check_in' => '2026-09-20', 'check_out' => '2026-09-23', 'notify_similar' => true]);

        // Check the walk-in out → real departure-clean task via the checkout event → listener.
        app(CheckOutReservation::class)->handle($walkIn);

        // Phase 5 — DEMO reviews (through the real ReviewService). guest1's past stay (an operator ROOM) → a
        // PUBLISHED review + the operator's response (storefront double room + operator). guest2's walk-in (an
        // OWNER apartment) → a PUBLISHED review (so the OWNER + the apartment storefront show real data). Real
        // data, flagged demo like every guest row.
        $reviews = app(ReviewService::class);
        $g1Review = $reviews->submit($guest1, $pastStay->fresh(), ['rating' => 5, 'tags' => ['Great location', 'Spotless villa'], 'body' => 'A wonderful stay — spotless and superbly located. We’ll be back.']);
        $reviews->publish($g1Review);
        $reviews->respond($g1Review, 'Thank you so much — it was a pleasure hosting you. Come back soon!');
        $g2Review = $reviews->submit($guest2, $walkIn->fresh(), ['rating' => 4, 'tags' => ['Comfy beds'], 'body' => 'Comfortable and central. Check-in took a little while.']);
        $reviews->publish($g2Review);

        // --- Owner accounting (the wedge) — the demo user IS a property owner of the apartments ---
        // Real + coherent: attribution reads the folios, the statement is a pure ledger projection,
        // the payout is created from the finalized statement. Nothing fabricated.
        $ownerParty = $this->seedOwnerAccounting($owner, $property, $apartment, $aptRate, $aptUnits, $vat, $walkIn);

        // DEMO ONLY — the owner's monthly NET goal, so the Bookings page's "Monthly goal" ring + the chart's
        // goal line render on a fresh demo. This is a real owner SETTING (a value the owner would type), not a
        // fabricated figure: the ring still divides the REAL current-month net by it, so early in the month it
        // honestly reads a low %, not a staged 123%.
        OwnerMonthlyTarget::updateOrCreate(
            ['owner_id' => $ownerParty->id, 'currency' => 'EUR'],
            ['organization_id' => $org->id, 'target_minor' => 600000],   // €6,000 / month
        );

        // --- Owner ↔ operator messages (Wave 3) — real threads via the real InboxService, so the owner
        // Messages screen (and the operator's inbox) demo on genuine data.
        $this->seedOwnerMessages($ownerParty, $staff);

        // --- Maintenance — a coherent spread so the styled board + work order demo the module. Every
        // ticket is created through the real MaintenanceService (guarded lifecycle, real events, the real
        // out-of-service ↔ availability + cost → owner-expense hooks) — never a raw insert. Runs AFTER
        // owner accounting so the apartment owner_id is set (the owned-unit cost posts a real expense).
        $this->seedMaintenance($roomUnits, $aptUnits, $staff);

        // --- Unified Inbox — coherent guest conversations through the REAL InboxService (no raw inserts):
        // a linked pre-arrival question (+ operator reply), an unlinked stranger enquiry, a resolved thread.
        $this->seedInbox($staff, $guest1, $stay1, $guest2);

        // --- Channel manager (Channex) — a CONNECTED demo channel + ACTIVE room-type/rate-plan mappings, so the
        // (Phase 1) Channels screen has real data and the certified ARI-push pipeline is armed. Both statuses are
        // written through the real ChannelConnectionService (the writer that was missing — nothing else sets
        // 'connected'/'active', which left the channel manager inert in production). The live Channex sync itself
        // stays account-gated. Seeded LAST so no already-created demo stay retroactively enqueues a push.
        $this->seedChannel($property, $doubleRoom, $apartment, $roomRate, $aptRate);

        // Phase 7b — a real subscription for the demo org so billing is demoable. ACTIVE on ESSENTIAL: an
        // established paying operator (seeded DEMO data, like every row here — the product never flips an org
        // to active off a fake payment; the live charge stays account-gated). Essential also demos the REAL
        // feature gate — Channels shows a "Pro" lock in the nav.
        $essentialPlan = Plan::query()->where('code', 'essential_monthly')->first();
        if ($essentialPlan !== null) {
            Subscription::firstOrCreate(
                ['organization_id' => $org->id],
                ['plan_id' => $essentialPlan->id, 'status' => 'active', 'current_period_end' => now()->addMonth()],
            );
        }

        // Phase 7d — TEAM SCHEDULE: a demo week of real shifts on the seaside property + an approved leave + a
        // pending time-off request, so the roster + the schedule PDF + the approval queue demo on real state.
        $this->seedTeamSchedule($property, $staff, $accountant, $admin);

